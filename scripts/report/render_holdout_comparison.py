#!/usr/bin/env python3
"""
Render the four-figure holdout comparison used in the thesis progress
reports: a strip of N frames from one holdout cell, shown as (1) raw
unannotated frames, (2) the multiclass ground-truth annotation (rendered via
scripts/annotation/preview_masks.py's own color convention — not a re-drawn
approximation), (3) ground truth vs. U-Net prediction on a black background
(mask-only, no frame texture), and (4) the same comparison overlaid on the
original frame.

Each panel carries its own frame index in a label band above the image, so a
figure in a report can be traced back to specific files on disk (disable with
--no-frame-labels). All four images share one crop window and panel size so the
cell renders at the same scale in every figure — that consistency was the whole point of
writing this as a real script instead of one-off code. The crop is centered
on the trapped cell and auto-sized to comfortably contain the ground truth,
nearby decoy objects, and the largest predicted region across the chosen
frames (see --pad / --decoy-radius), or pass --half-width/--half-height to
pin it explicitly.

This exists because the images embedded in the 2026-09-03 progress report
(figs. 2-5, `high-cell9`, `bf32_reg2_cos` checkpoint) were originally
generated as disposable inline scripts, regenerated by hand every time a
color/crop request came in. Re-run this whenever that comparison needs to be
regenerated (new cell, new checkpoint, a palette tweak) instead of writing
another one-off script.

Usage
-----
python scripts/report/render_holdout_comparison.py \\
    --pool 02_unet_holdout --cell high_cell9 \\
    --checkpoint checkpoints/preswap/stage_3_regularisation/multiclass_experiment_256_bf32_reg2_cos/unet_best.pt

python scripts/report/render_holdout_comparison.py \\
    --pool 02_unet_holdout --cell low_cell6 \\
    --checkpoint checkpoints/preswap/stage_1_labels_and_resolution/multiclass_experiment_256/unet_best.pt \\
    --base-features 64 --n-frames 5 --output-dir results/holdout_comparisons/low_cell6

python scripts/report/render_holdout_comparison.py --pool 02_unet_holdout --cell high_cell9 \\
    --checkpoint checkpoints/preswap/stage_3_regularisation/multiclass_experiment_256_bf32_reg2_cos/unet_best.pt \\
    --gt-color 0,60,255 --half-width 140 --half-height 140   # pin crop + palette explicitly

# The deployed configuration: four checkpoints run as one EnsembleUNet, panels
# labelled by laser increment rather than frame index.
python scripts/report/render_holdout_comparison.py --pool 02_unet_holdout --cell high_cell1 \\
    --checkpoint checkpoints/postswap/experiment_0a_seed_baseline/postswap_ftl_cw142_s4{2,3,4,5}/unet_best.pt \\
    --power-labels 200 --n-frames 6
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2
import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).parent.parent.parent))  # repo root
from celldform.segmentation.unet import UNet
from celldform.segmentation.ensemble import EnsembleUNet

sys.path.insert(0, str(Path(__file__).parent.parent / "annotation"))  # for preview_masks
from preview_masks import _colorize  # the real color convention, not a re-implementation

_EXTS = (".jpg", ".jpeg", ".png")


def _rgb_to_bgr(spec: str) -> tuple[int, int, int]:
    r, g, b = (int(x) for x in spec.split(","))
    return (b, g, r)


def _find(directory: Path, stem: str) -> Path:
    for ext in _EXTS:
        candidate = directory / f"{stem}{ext}"
        if candidate.exists():
            return candidate
    sys.exit(f"No file found for stem '{stem}' in {directory}")


def _select_frame_indices(frame_dir: Path, cell: str, n: int) -> list[str]:
    """Evenly-spaced 6-digit frame index strings for `cell`, sorted."""
    stems = sorted(
        p.stem for p in frame_dir.iterdir()
        if p.suffix.lower() in _EXTS and p.stem.startswith(f"{cell}_")
    )
    if not stems:
        sys.exit(f"No frames found for cell '{cell}' in {frame_dir}")
    idxs = [s[len(cell) + 1:] for s in stems]
    if n >= len(idxs):
        return idxs
    positions = np.linspace(0, len(idxs) - 1, n).round().astype(int)
    return [idxs[i] for i in sorted(set(positions.tolist()))]


def _auto_crop(gt_masks: list[np.ndarray], preds: list[np.ndarray],
                decoy_radius: float, pad: int) -> tuple[int, int, int, int]:
    """Union bbox of the trapped cell, nearby decoys, and predictions across
    frames, padded — the crop window shared by all four output figures."""
    x0 = y0 = 10**9
    x1 = y1 = -1
    for gt, pred in zip(gt_masks, preds):
        cell_ys, cell_xs = np.where(gt == 1)
        if len(cell_xs) == 0:
            continue
        ccx, ccy = cell_xs.mean(), cell_ys.mean()

        decoy = (gt == 2).astype(np.uint8)
        n, _labels, stats, centroids = cv2.connectedComponentsWithStats(decoy, connectivity=8)
        for i in range(1, n):
            x, y, w, h, _area = stats[i]
            cx, cy = centroids[i]
            if ((cx - ccx) ** 2 + (cy - ccy) ** 2) ** 0.5 < decoy_radius:
                x0, x1 = min(x0, x), max(x1, x + w)
                y0, y1 = min(y0, y), max(y1, y + h)

        x0, x1 = min(x0, cell_xs.min()), max(x1, cell_xs.max())
        y0, y1 = min(y0, cell_ys.min()), max(y1, cell_ys.max())

        pys, pxs = np.where(pred > 0)
        if len(pxs):
            x0, x1 = min(x0, pxs.min()), max(x1, pxs.max())
            y0, y1 = min(y0, pys.min()), max(y1, pys.max())

    if x1 < 0:
        sys.exit("No trapped-cell pixels found in any selected frame — cannot auto-crop.")
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    half_w = (x1 - x0) // 2 + pad
    half_h = (y1 - y0) // 2 + pad
    return cx, cy, half_w, half_h


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Render the raw/labelled-mask/masks-only/overlay holdout comparison strip")
    parser.add_argument("--pool", default="02_unet_holdout",
                        help="Pool folder name under data/frames/ and data/preprocessed/evaluate/")
    parser.add_argument("--cell", required=True, help="Cell filename prefix, e.g. high_cell9")
    parser.add_argument("--mask-dir", type=Path, help="Override GT mask directory "
                        "(default: data/masks/<pool>_multiclass)")
    parser.add_argument("--frame-dir", type=Path, help="Override raw frame directory "
                        "(default: data/frames/<pool>)")
    parser.add_argument("--preprocessed-dir", type=Path, help="Override preprocessed input directory "
                        "(default: data/preprocessed/evaluate/<pool>/inputs)")

    parser.add_argument("--checkpoint", type=Path, required=True, nargs="+",
                        help="One checkpoint, or several to run them as an ensemble "
                             "(EnsembleUNet: averaged softmax, the deployed configuration)")
    parser.add_argument("--base-features", type=int, default=None,
                        help="Overrides the checkpoint dir's own config.yaml when given")
    parser.add_argument("--out-channels", type=int, default=None)
    parser.add_argument("--in-channels", type=int, default=None)

    parser.add_argument("--n-frames", type=int, default=5,
                        help="Evenly-spaced frames to render (ignored if --frame-indices given)")
    parser.add_argument("--frame-indices", type=str, default=None,
                        help="Comma-separated 6-digit frame indices, e.g. 000000,002000,004000")

    parser.add_argument("--half-width", type=int, default=None, help="Pin crop half-width in px")
    parser.add_argument("--half-height", type=int, default=None, help="Pin crop half-height in px")
    parser.add_argument("--pad", type=int, default=45,
                        help="Padding (px) added around the auto-computed union bbox")
    parser.add_argument("--decoy-radius", type=float, default=150.0,
                        help="Max distance (px) from the trapped-cell centroid for a decoy blob "
                             "to count toward the auto-crop (excludes far-flung debris)")

    parser.add_argument("--frame-labels", dest="frame_labels", action="store_true", default=True,
                        help="Print each panel's frame index in a band above it (default)")
    parser.add_argument("--no-frame-labels", dest="frame_labels", action="store_false",
                        help="Render bare panels with no frame-index band")
    parser.add_argument("--power-labels", action="store_true",
                        help="Label panels by laser increment instead of frame index. The "
                             "acquisition ramps power in ~50 increments and frames are sampled "
                             "one per increment, so a frame's rank in the cell's full sorted "
                             "frame list IS its increment: 'step 20/50'. Derived from the rank, "
                             "not from a fixed frames-per-step divisor -- the videos are not all "
                             "the same length, and cell 1's last frame (010200) would come out "
                             "as step 51 of 50 under a fixed 200.")
    parser.add_argument("--label-color", type=str, default="255,255,255",
                        help="R,G,B for the frame-index text")
    parser.add_argument("--label-bg", type=str, default="20,20,20",
                        help="R,G,B for the frame-index band background")

    parser.add_argument("--alpha", type=float, default=0.55, help="Overlay blend strength (0-1)")
    parser.add_argument("--gt-color", type=str, default="0,60,255", help="R,G,B for ground truth")
    parser.add_argument("--pred-color", type=str, default="0,200,0", help="R,G,B for prediction")
    parser.add_argument("--overlap-color", type=str, default="220,220,0", help="R,G,B for overlap")
    parser.add_argument("--border-color", type=str, default="60,60,60", help="R,G,B panel border")

    parser.add_argument("--output-dir", type=Path, default=None,
                        help="Default: results/holdout_comparisons/<pool>_<cell>")
    parser.add_argument("--output-prefix", type=str, default=None, help="Default: <cell>")
    args = parser.parse_args()

    mask_dir = args.mask_dir or Path("data/masks") / f"{args.pool}_multiclass"
    frame_dir = args.frame_dir or Path("data/frames") / args.pool
    pre_dir = args.preprocessed_dir or Path("data/preprocessed/evaluate") / args.pool / "inputs"
    output_dir = args.output_dir or Path("results/holdout_comparisons") / f"{args.pool}_{args.cell}"
    prefix = args.output_prefix or args.cell

    for d, label in ((mask_dir, "mask"), (frame_dir, "frame"), (pre_dir, "preprocessed")):
        if not d.exists():
            sys.exit(f"{label.capitalize()} directory not found: {d}")

    missing = [c for c in args.checkpoint if not c.exists()]
    if missing:
        sys.exit(f"Checkpoint(s) not found: {missing}")

    base_features, out_channels, in_channels = args.base_features, args.out_channels, args.in_channels
    if None in (base_features, out_channels, in_channels):
        sibling_config = args.checkpoint[0].parent / "config.yaml"
        if sibling_config.exists():
            # Full (not safe_load) — SegmentationTrainer's saved snapshot uses a
            # !!python/tuple tag for preprocessing.target_size; this file is our
            # own trainer-generated output, not untrusted input.
            with open(sibling_config) as fh:
                raw = yaml.load(fh, Loader=yaml.UnsafeLoader) or {}
            unet_cfg = raw.get("unet", {})
            base_features = base_features if base_features is not None else unet_cfg.get("base_features", 64)
            out_channels = out_channels if out_channels is not None else unet_cfg.get("out_channels", 3)
            in_channels = in_channels if in_channels is not None else unet_cfg.get("in_channels", 1)
        else:
            base_features = base_features if base_features is not None else 64
            out_channels = out_channels if out_channels is not None else 3
            in_channels = in_channels if in_channels is not None else 1
            print(f"Warning: no config.yaml next to {args.checkpoint[0]}, "
                  f"assuming base_features={base_features}, out_channels={out_channels}, "
                  f"in_channels={in_channels}")

    if len(args.checkpoint) == 1:
        model = UNet.from_checkpoint(args.checkpoint[0], in_channels=in_channels,
                                     base_features=base_features, out_channels=out_channels)
        print(f"Model: single checkpoint {args.checkpoint[0]}")
    else:
        # The same class RealTimePipeline runs, so these panels show the deployed
        # prediction rather than a figure-only reimplementation of averaging.
        model = EnsembleUNet.from_checkpoints(args.checkpoint, in_channels=in_channels,
                                              out_channels=out_channels,
                                              base_features=base_features)
        print(f"Model: ensemble of {len(model)}")
        for c in args.checkpoint:
            print(f"  - {c}")

    if args.frame_indices:
        idxs = [s.strip() for s in args.frame_indices.split(",")]
    else:
        idxs = _select_frame_indices(frame_dir, args.cell, args.n_frames)
    print(f"Frames: {', '.join(idxs)}")

    power_label: dict[str, str] = {}
    if args.power_labels:
        all_idxs = _select_frame_indices(frame_dir, args.cell, 10**9)  # every frame, sorted
        last = len(all_idxs) - 1
        rank = {v: i for i, v in enumerate(all_idxs)}
        power_label = {i: f"step {rank[i]}/{last}" for i in idxs}
        print(f"Laser ramp: {len(all_idxs)} increments, "
              f"showing {', '.join(power_label[i] for i in idxs)}")

    gt_masks, preds, frames = [], [], []
    raw_h = raw_w = None
    for idx in idxs:
        frame = cv2.imread(str(_find(frame_dir, f"{args.cell}_{idx}")), cv2.IMREAD_GRAYSCALE)
        gt = cv2.imread(str(_find(mask_dir, f"{args.cell}_{idx}")), cv2.IMREAD_GRAYSCALE)
        raw_h, raw_w = frame.shape

        pre = cv2.imread(str(_find(pre_dir, f"{args.cell}_{idx}")), cv2.IMREAD_GRAYSCALE)
        pred_small = model.predict(pre.astype(np.float32) / 255.0, binary_output=True)
        pred = cv2.resize(pred_small, (raw_w, raw_h), interpolation=cv2.INTER_NEAREST)

        frames.append(frame)
        gt_masks.append(gt)
        preds.append(pred)

    if args.half_width is not None and args.half_height is not None:
        # Pinned crop size — still center on the trapped cell's own extent,
        # falling back to the frame center if no frame has one.
        all_cell_x, all_cell_y = [], []
        for gt in gt_masks:
            ys, xs = np.where(gt == 1)
            if len(xs):
                all_cell_x.append(xs.mean())
                all_cell_y.append(ys.mean())
        cx, cy = (int(np.mean(all_cell_x)), int(np.mean(all_cell_y))) if all_cell_x \
            else (raw_w // 2, raw_h // 2)
        half_w, half_h = args.half_width, args.half_height
    else:
        cx, cy, half_w, half_h = _auto_crop(gt_masks, preds, args.decoy_radius, args.pad)
    print(f"Crop: center=({cx},{cy}) half_size=({half_w},{half_h})")

    x0, y0 = cx - half_w, cy - half_h
    w, h = 2 * half_w, 2 * half_h
    border_bgr = _rgb_to_bgr(args.border_color)

    label_bgr = _rgb_to_bgr(args.label_color)
    label_bg_bgr = _rgb_to_bgr(args.label_bg)
    band_h = max(20, int(round(h * 0.085))) if args.frame_labels else 0
    font = cv2.FONT_HERSHEY_SIMPLEX
    font_scale = max(0.4, band_h / 40.0)
    thickness = max(1, int(round(font_scale * 1.6)))

    def crop(img_bgr: np.ndarray, label: str | None = None) -> np.ndarray:
        c = img_bgr[y0:y0 + h, x0:x0 + w]
        c = cv2.copyMakeBorder(c, 1, 1, 1, 1, cv2.BORDER_CONSTANT, value=border_bgr)
        if not args.frame_labels or label is None:
            return c
        band = np.full((band_h, c.shape[1], 3), label_bg_bgr, dtype=np.uint8)
        (tw, th), _ = cv2.getTextSize(label, font, font_scale, thickness)
        cv2.putText(band, label, ((c.shape[1] - tw) // 2, (band_h + th) // 2),
                    font, font_scale, label_bgr, thickness, cv2.LINE_AA)
        band[-1, :] = border_bgr
        return np.vstack([band, c])

    gt_color = _rgb_to_bgr(args.gt_color)
    pred_color = _rgb_to_bgr(args.pred_color)
    overlap_color = _rgb_to_bgr(args.overlap_color)

    raw_panels, labelled_panels, masksonly_panels, overlay_panels = [], [], [], []
    for idx, frame, gt, pred in zip(idxs, frames, gt_masks, preds):
        frame_bgr = cv2.cvtColor(frame, cv2.COLOR_GRAY2BGR)
        gt_bin = (gt == 1).astype(np.uint8)
        label = power_label[idx] if args.power_labels else f"frame {idx}"

        raw_panels.append(crop(frame_bgr, label))
        labelled_panels.append(crop(_colorize(gt), label))

        only_gt = (gt_bin > 0) & (pred == 0)
        only_pred = (pred > 0) & (gt_bin == 0)
        overlap = (gt_bin > 0) & (pred > 0)

        color_layer = np.zeros_like(frame_bgr)
        color_layer[only_gt] = gt_color
        color_layer[only_pred] = pred_color
        color_layer[overlap] = overlap_color
        painted = np.any(color_layer != 0, axis=2)

        masksonly_panels.append(crop(color_layer, label))

        blended_full = cv2.addWeighted(frame_bgr, 1 - args.alpha, color_layer, args.alpha, 0)
        overlay = frame_bgr.copy()
        overlay[painted] = blended_full[painted]
        overlay_panels.append(crop(overlay, label))

    output_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "raw": np.hstack(raw_panels),
        "labelled_mask": np.hstack(labelled_panels),
        "masks_only": np.hstack(masksonly_panels),
        "overlay": np.hstack(overlay_panels),
    }
    for name, img in outputs.items():
        out_path = output_dir / f"{prefix}_{name}.png"
        cv2.imwrite(str(out_path), img)
        print(f"  -> {out_path}")

    print(f"\nDone. Legend: ground truth {args.gt_color} (R,G,B), "
          f"prediction {args.pred_color}, overlap {args.overlap_color}. "
          "Labelled-mask panel uses scripts/annotation/preview_masks.py's own convention "
          "(green=trapped cell, red=decoy) unaffected by --gt-color/--pred-color.")


if __name__ == "__main__":
    main()
