#!/usr/bin/env python3
"""
The four candidate segmenters side by side, on the same 15 cross-validated cells: one small panel
per measure, every value labelled. Used by the report to choose the deployment models.

    python scripts/report/plot_model_comparison.py --out ../masters_thesis/images \
        --tables ../masters_thesis/main_work/tables

Models: ours (CV model), nnU-Net (teacher), the ensemble (ours + nnU-Net, 0.5/0.5) and MegaNet (the
student distilled from nnU-Net). Accuracy comes from each model's <run>_cv_cells.csv (every cell scored
by the round that held it out); speed from results/randswap/experiment_1_nnunet/latency_ms.json (all four
timed in one session, raw frame -> features). Each panel has its own axis -- fps never shares a scale
with Dice. Writes model_comparison.png and model_comparison.tex.
"""
from __future__ import annotations

import argparse
import csv
import json
import statistics as st
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = Path("results/randswap")
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e6e5e1", "#fcfcfb"
CAMERA_FPS = 22
MODELS = [  # label, results folder, run, colour (report series), latency key
    ("U-Net", "experiment_0_cv_baseline", "cv_baseline", "#4a3aa7", "ours_crop384"),
    ("nnU-Net", "experiment_1_nnunet", "nnunet", "#b0306a", "nnunet_tta"),
    ("Ensemble", "experiment_2_ensemble", "ensemble", "#3d3d3a", "ensemble_tta"),
    ("MegaNet", "experiment_3_distill/cv", "student_cv", "#7a4a00", "meganet"),
]


def measures() -> list[dict]:
    lat = json.loads((R / "experiment_1_nnunet" / "latency_ms.json").read_text())
    out = []
    for label, exp, run, col, lk in MODELS:
        cells = list(csv.DictReader((R / exp / f"{run}_cv_cells.csv").open()))
        tp, fp, fn = (sum(int(c[k]) for c in cells) for k in ("tp", "fp", "fn"))
        d = [float(c["dsc"]) for c in cells]
        hi = [float(c["dsc"]) for c in cells if c["her2"] == "high"]
        worst = min(cells, key=lambda c: float(c["dsc"]))
        out.append({"label": label, "colour": col, "pooled": 2 * tp / (2 * tp + fp + fn),
                    "mean": st.mean(d), "high": st.mean(hi), "worst": float(worst["dsc"]),
                    "worst_cell": worst["cell"].replace("_cell", "-"), "ms": lat[lk], "fps": 1000 / lat[lk]})
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--tables", type=Path, required=True)
    a = ap.parse_args()
    M = measures()
    panels = [("pooled", "Pooled DSC", "all 15 cells"), ("mean", "Per-cell mean DSC", "each cell equal"),
              ("high", "High-HER2 mean DSC", "the 9 harder cells"), ("worst", "Worst cell DSC", "any one cell"),
              ("fps", "Frames per second", f"camera: {CAMERA_FPS} fps")]
    fig, axes = plt.subplots(1, len(panels), figsize=(12.6, 3.2), facecolor="white", sharey=True,
                             gridspec_kw={"wspace": 0.12})
    ys = list(range(len(M)))[::-1]
    for ax, (k, title, sub) in zip(axes, panels):
        ax.set_facecolor(SURF)
        for sp in ("top", "right", "left"):
            ax.spines[sp].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(colors=INK2, labelsize=8, length=0)
        ax.grid(axis="x", color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        vals = [m[k] for m in M]
        ax.barh(ys, vals, height=0.56, color=[m["colour"] for m in M], zorder=2)
        top = max(vals)
        for y, m, v in zip(ys, M, vals):
            txt = f"{v:.0f}" if k == "fps" else f"{v:.3f}"
            if k == "worst":
                txt += f"  {m['worst_cell']}"
            ax.text(v + top * 0.03, y, txt, va="center", ha="left", fontsize=8.2, color=INK)
        if k == "fps":
            ax.axvline(CAMERA_FPS, color="#e34948", lw=1.2, ls=(0, (4, 3)), zorder=3)
            ax.text(CAMERA_FPS + 0.6, ys[0] + 0.55, "real time", color="#b02a2a", fontsize=7.6, va="center")
            ax.set_xlim(0, 36)
        else:
            ax.set_xlim(0, 1.42 if k == "worst" else 1.18)      # room for the cell name
            ax.set_xticks([0, 0.5, 1.0])
        ax.set_title(f"{title}\n", loc="left", fontsize=9.4, color=INK, fontweight="bold")
        ax.text(0, 1.02, sub, transform=ax.transAxes, fontsize=7.8, color=INK2)
    axes[0].set_yticks(ys, [m["label"] for m in M], fontsize=9.4, color=INK)
    fig.savefig(a.out / "model_comparison.png", dpi=200, bbox_inches="tight", facecolor="white")
    plt.close(fig)

    best = {k: max(m[k] for m in M) for k in ("pooled", "mean", "high", "worst", "fps")}
    b = lambda k, m, s: rf"\textbf{{{s}}}" if m[k] == best[k] else s
    lines = [r"% GENERATED by scripts/report/plot_model_comparison.py -- do not edit by hand.",
             r"\begin{tabular}{lccccc}", r"\toprule",
             r" & \textbf{Pooled DSC} & \textbf{Per-cell mean} & \textbf{High HER2} & \textbf{Worst cell} & "
             r"\textbf{Time per frame} \\", r"\midrule"]
    for m in M:
        lines.append(" & ".join([m["label"], b("pooled", m, f"{m['pooled']:.3f}"), b("mean", m, f"{m['mean']:.3f}"),
                                 b("high", m, f"{m['high']:.3f}"), b("worst", m, f"{m['worst_cell']} {m['worst']:.3f}"),
                                 b("fps", m, f"{m['ms']:.0f} ms ({m['fps']:.0f} fps)")]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (a.tables / "model_comparison.tex").write_text("\n".join(lines))
    print(f"-> {a.out / 'model_comparison.png'}, {a.tables / 'model_comparison.tex'}")


if __name__ == "__main__":
    main()
